"""Auxiliary regeneration tools for confinement diagnostics.

The original plotting logic is spread over the final cells of
``confinementv3.ipynb``.  This script is the active Paper-A reproducer for:

* the Fig. 1 A/B ED--TDVP defect-profile layout generated with one common
  pole-regularization protocol;
* an auxiliary A/B defect-site Bloch comparison (the revised manuscript's
  Fig. 2 is generated by ``explore_resonance_mode_transition.py``);
* optional same-ring diagnostics retained for development but not used by
  Paper A.

The active manuscript uses the regenerated leakage-map composite and the
Bloch-plane portraits.  Every active panel uses ``theta_pole=1e-3`` and
``phi_i=0``.  Caches from any older initialization are rejected by the
current cache validator.

The script also writes optional ED and TDVP defect-response widths to
``output/defect_widths.csv`` and JSON.

All newly generated spin-1/2 trajectories use the specialized TDVP flow in
``tdvpfun``.  The generic-spin notebook helper is retained only as provenance
for the archived leakage scan and is not used to generate new profiles.

Run from this directory with the QuSpin environment, for example

    conda run -n quspin python reproduce_fig1_fig2.py --figures profiles

The Appendix-F validation alone is produced by

    conda run -n quspin python reproduce_fig1_fig2.py \
      --figures bounds --recompute-bounds

The leakage cache in ``data`` is generated by
``explore_resonance_mode_transition.py`` and records the complete numerical
protocol.  Before plotting, this script verifies its grid, time window,
solver, pole bias, and fixed initial phase.

Newly regenerated auxiliary ED/TDVP panels use ``K=100`` and ``L=24``.  The
former Appendix-F validation instead uses a common ``L=K=14`` ring, as
required by that theorem.  Both regeneration paths now follow the Paper-A
initialization ``theta_pole=1e-3``, ``phi_i=0``, and DOP853 with
``rtol=1e-9``, ``atol=1e-11``, and ``max_step=0.02``.  The more expensive
trajectories are generated once and cached.  Use ``--recompute-core``,
``--recompute-phase``, or ``--recompute-bounds`` to refresh them.
"""

