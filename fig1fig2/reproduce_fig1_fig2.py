class FiniteMPSRing:
    """Fast finite-ring evaluation of the normalized bond-dimension-2 MPS."""

    def __init__(self, basis, length: int):
        self.length = length
        self.dimension = int(basis.Ns)
        states = np.asarray([int(basis[index]) for index in range(basis.Ns)])
        powers = 2 ** np.arange(length - 1, -1, -1, dtype=np.int64)
        self.occupations = ((states[:, None] // powers[None, :]) % 2).astype(int)

    def state(self, theta: np.ndarray, phi: np.ndarray) -> np.ndarray:
        theta = np.asarray(theta, dtype=float)
        phi = np.asarray(phi, dtype=float)
        if theta.shape != (self.length,) or phi.shape != (self.length,):
            raise ValueError("Finite-ring MPS angles have the wrong shape.")
        matrices = np.zeros((self.length, 2, 2, 2), dtype=complex)
        matrices[:, 0, 0, 0] = np.cos(theta / 2.0)
        matrices[:, 0, 1, 0] = 1.0
        matrices[:, 1, 0, 1] = np.sin(theta / 2.0) * np.exp(-1j * phi)
        product = np.broadcast_to(
            np.eye(2, dtype=complex), (self.dimension, 2, 2)
        ).copy()
        for site in range(self.length):
            selected = matrices[site, self.occupations[:, site]]
            product = np.einsum("nij,njk->nik", product, selected, optimize=True)
        coefficients = np.trace(product, axis1=1, axis2=2)
        norm = np.linalg.norm(coefficients)
        if not np.isfinite(norm) or norm <= 0.0:
            raise RuntimeError("Finite-ring MPS has zero or invalid norm.")
        return coefficients / norm


def _bound_basis_and_local_paulis(length: int):
    """Construct the shared QuSpin basis and restricted one-site Paulis."""

    from quspin.operators import hamiltonian

    basis = pxpbasisS.constrained_basis(2, length, None, None)
    no_checks = dict(check_symm=False, check_pcon=False, check_herm=False)
    operators = []
    for site in range(length):
        operators.extend(
            [
                hamiltonian(
                    [["+", [[1.0, site]]], ["-", [[1.0, site]]]],
                    [],
                    basis=basis,
                    dtype=np.complex128,
                    **no_checks,
                ).static.tocsr(),
                hamiltonian(
                    [["+", [[-1j, site]]], ["-", [[1j, site]]]],
                    [],
                    basis=basis,
                    dtype=np.complex128,
                    **no_checks,
                ).static.tocsr(),
                hamiltonian(
                    [["z", [[2.0, site]]]],
                    [],
                    basis=basis,
                    dtype=np.complex128,
                    **no_checks,
                ).static.tocsr(),
            ]
        )
    return basis, operators


def _bound_hamiltonian(basis, length: int, mu: float, chi: float):
    """Return the same staggered PXP Hamiltonian used by the existing ED code."""

    from quspin.operators import hamiltonian

    delta = np.asarray(
        [2.0 * mu - chi, 2.0 * mu + chi] * (length // 2), dtype=float
    )
    static = [
        ["+", [[1.0, site] for site in range(length)]],
        ["-", [[1.0, site] for site in range(length)]],
        ["z", [[2.0 * delta[site], site] for site in range(length)]],
    ]
    no_checks = dict(check_symm=False, check_pcon=False, check_herm=False)
    return hamiltonian(
        static,
        [],
        basis=basis,
        dtype=np.complex128,
        **no_checks,
    ).static.tocsr()


def _tile_path_coordinates(y: np.ndarray, period: int, length: int) -> tuple[np.ndarray, np.ndarray]:
    if length % period != 0:
        raise ValueError("The variational period must divide the finite ring.")
    repetitions = length // period
    return np.tile(y[:period], repetitions), np.tile(y[period:], repetitions)


def _finite_residual(
    builder: FiniteMPSRing,
    hamiltonian_sparse,
    state: np.ndarray,
    y: np.ndarray,
    ydot: np.ndarray,
    period: int,
) -> tuple[float, float]:
    """Finite-difference the normalized MPS path and project its residual."""

    theta, phi = _tile_path_coordinates(y, period, builder.length)
    dtheta, dphi = _tile_path_coordinates(ydot, period, builder.length)
    direction_scale = max(float(np.max(np.abs(np.concatenate((dtheta, dphi))))), 1.0)

    def directional_derivative(displacement: float) -> np.ndarray:
        step = displacement / direction_scale
        state_plus = builder.state(theta + step * dtheta, phi + step * dphi)
        state_minus = builder.state(theta - step * dtheta, phi - step * dphi)
        return (state_plus - state_minus) / (2.0 * step)

    coarse = directional_derivative(1.0e-5)
    fine = directional_derivative(5.0e-6)
    derivative = (4.0 * fine - coarse) / 3.0
    fd_relative = float(
        np.linalg.norm(derivative - fine) / max(np.linalg.norm(derivative), 1.0e-14)
    )
    residual = derivative + 1j * (hamiltonian_sparse @ state)
    residual -= state * np.vdot(state, residual)
    gamma = float(np.linalg.norm(residual) / np.sqrt(builder.length))
    return gamma, fd_relative


def _variational_states_and_residuals(
    builder: FiniteMPSRing,
    hamiltonian_sparse,
    trajectory: np.ndarray,
    times: np.ndarray,
    mu: float,
    chi: float,
    period: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    states = np.empty((builder.dimension, times.size), dtype=complex)
    gamma = np.empty(times.size, dtype=float)
    fd_relative = np.empty(times.size, dtype=float)
    for time_index, current_time in enumerate(times):
        y = trajectory[:, time_index]
        theta, phi = _tile_path_coordinates(y, period, builder.length)
        states[:, time_index] = builder.state(theta, phi)
        ydot = tdvpfun.eom(float(current_time), y, mu, chi)
        gamma[time_index], fd_relative[time_index] = _finite_residual(
            builder,
            hamiltonian_sparse,
            states[:, time_index],
            y,
            ydot,
            period,
        )
    return states, gamma, fd_relative


def _diagonalize(hamiltonian_sparse) -> tuple[np.ndarray, np.ndarray]:
    eigenvalues, eigenvectors = np.linalg.eigh(hamiltonian_sparse.toarray())
    return eigenvalues, eigenvectors


def _propagate_columns(
    eigenvalues: np.ndarray,
    eigenvectors: np.ndarray,
    states: np.ndarray,
    durations: np.ndarray,
) -> np.ndarray:
    coefficients = eigenvectors.conj().T @ states
    coefficients = coefficients * np.exp(
        -1j * eigenvalues[:, None] * durations[None, :]
    )
    return eigenvectors @ coefficients


def _time_indices(grid: np.ndarray, requested: np.ndarray) -> np.ndarray:
    indices = np.searchsorted(grid, requested)
    if np.any(indices >= grid.size) or not np.allclose(
        grid[indices], requested, rtol=0.0, atol=1.0e-12
    ):
        raise ValueError("Requested bound times are absent from the trajectory grid.")
    return indices


def _bloch_vectors(states: np.ndarray, local_paulis: list) -> np.ndarray:
    values = []
    for operator in local_paulis:
        acted = operator @ states
        values.append(np.sum(states.conj() * acted, axis=0).real)
    return np.asarray(values).reshape(-1, 3, states.shape[1])


def _covariance_largest_eigenvalue(state: np.ndarray, local_paulis: list) -> float:
    actions = np.column_stack([operator @ state for operator in local_paulis])
    means = (state.conj() @ actions).real
    covariance = (actions.conj().T @ actions).real - np.outer(means, means)
    covariance = 0.5 * (covariance + covariance.T)
    return float(max(0.0, np.linalg.eigvalsh(covariance)[-1]))


def _one_site_errors(
    exact_states: np.ndarray,
    variational_states: np.ndarray,
    local_paulis: list,
) -> tuple[np.ndarray, np.ndarray]:
    exact_bloch = _bloch_vectors(exact_states, local_paulis)
    variational_bloch = _bloch_vectors(variational_states, local_paulis)
    trace_distance = 0.5 * np.linalg.norm(exact_bloch - variational_bloch, axis=1)
    exact_norm2 = np.sum(exact_bloch**2, axis=1)
    variational_norm2 = np.sum(variational_bloch**2, axis=1)
    fidelity = 0.5 * (
        1.0
        + np.sum(exact_bloch * variational_bloch, axis=1)
        + np.sqrt(
            np.maximum(0.0, 1.0 - exact_norm2)
            * np.maximum(0.0, 1.0 - variational_norm2)
        )
    )
    return np.mean(trace_distance, axis=0), np.mean(np.clip(fidelity, 0.0, 1.0), axis=0)


def _numerical_theorem_bound(
    times: np.ndarray,
    target_times: np.ndarray,
    source_times: np.ndarray,
    variational_states: np.ndarray,
    gamma: np.ndarray,
    eigenvalues: np.ndarray,
    eigenvectors: np.ndarray,
    local_paulis: list,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    target_indices = _time_indices(times, target_times)
    source_indices = _time_indices(times, source_times)
    largest = np.full((target_times.size, source_times.size), np.nan)
    bound = np.zeros(target_times.size)
    raw_simpson = np.zeros(target_times.size)
    quadrature_difference = np.zeros(target_times.size)
    for target_index, target_time in enumerate(target_times):
        mask = source_times <= target_time + 1.0e-12
        active_times = source_times[mask]
        active_indices = source_indices[mask]
        forward_states = _propagate_columns(
            eigenvalues,
            eigenvectors,
            variational_states[:, active_indices],
            target_time - active_times,
        )
        eigenvalue_row = np.asarray(
            [
                _covariance_largest_eigenvalue(forward_states[:, column], local_paulis)
                for column in range(forward_states.shape[1])
            ]
        )
        largest[target_index, mask] = eigenvalue_row
        if active_times.size < 2:
            continue
        integrand = gamma[active_indices] * np.sqrt(eigenvalue_row)
        trapezoid_value = float(np.trapezoid(integrand, active_times))
        simpson_value = float(simpson(integrand, x=active_times))
        raw_simpson[target_index] = simpson_value
        quadrature_difference[target_index] = abs(simpson_value - trapezoid_value)
        bound[target_index] = simpson_value + quadrature_difference[target_index]
    return bound, raw_simpson, quadrature_difference, largest


def _bond_profiles(states: np.ndarray, local_paulis: list, length: int) -> np.ndarray:
    z_operators = local_paulis[2::3]
    magnetization = np.vstack(
        [
            np.sum(states.conj() * (operator @ states), axis=0).real
            for operator in z_operators
        ]
    )
    occupation = 0.5 * (1.0 + magnetization)
    return occupation + np.roll(occupation, -1, axis=0)


def _width_trajectory(
    defect_profile: np.ndarray,
    background_profile: np.ndarray,
    center: int,
) -> tuple[np.ndarray, np.ndarray]:
    difference = np.abs(defect_profile - background_profile)
    weight = np.sum(difference, axis=0)
    probability = np.divide(
        difference,
        weight[None, :],
        out=np.zeros_like(difference),
        where=weight[None, :] > 1.0e-14,
    )
    direct_distance = np.abs(np.arange(defect_profile.shape[0]) - center)
    periodic_distance = np.minimum(direct_distance, defect_profile.shape[0] - direct_distance)
    width = np.sqrt(np.sum(periodic_distance[:, None] ** 2 * probability, axis=0))
    return width, weight


def _cumulative_average(values: np.ndarray, times: np.ndarray) -> np.ndarray:
    integral = cumulative_trapezoid(values, times, initial=0.0)
    average = np.divide(integral, times, out=np.zeros_like(integral), where=times > 0.0)
    average[0] = values[0]
    return average


def _analytic_susceptibility(
    trajectory: np.ndarray,
    period: int,
    length: int,
    times: np.ndarray,
    block_size: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    tiled_theta = np.tile(trajectory[:period], (length // period, 1))
    beta = np.abs(np.prod(-np.sin(tiled_theta / 2.0) ** 2, axis=0))
    beta_star = np.maximum.accumulate(beta)
    clipped = np.clip(beta_star, 1.0e-300, 1.0 - 1.0e-15)
    xi = np.maximum(1.0, -length / np.log(clipped))
    zeta = xi + 2.0 / PXP_KAPPA_STAR
    locality_prefactor = (
        64.0
        * np.exp(PXP_KAPPA_STAR)
        * (block_size + 2.0)
        / (
            (3.0 + 4.0 * np.cosh(PXP_KAPPA_STAR))
            * (1.0 - np.exp(-PXP_KAPPA_STAR))
        )
    )
    covariance_prefactor = 4.0 * np.exp(PXP_KAPPA_STAR) * locality_prefactor + 1.0
    core_radius = np.ceil(3.0 * length + 2.0 * PXP_VELOCITY_CONSTANT * times)
    susceptibility = (
        2.0 * block_size
        + 1.0
        + 2.0 * core_radius
        + 2.0 * covariance_prefactor / np.expm1(1.0 / zeta)
    )
    return susceptibility, beta_star, xi


def _conditional_width_bound(
    epsilon: np.ndarray,
    variational_weight_floor: np.ndarray,
    radius: float,
) -> tuple[np.ndarray, np.ndarray]:
    valid = epsilon < variational_weight_floor
    rhs = np.full_like(epsilon, np.nan)
    ratio = np.divide(
        2.0 * epsilon[valid],
        variational_weight_floor[valid] - epsilon[valid],
    )
    rhs[valid] = radius * np.minimum(1.0, np.sqrt(np.maximum(0.0, ratio)))
    return rhs, valid


def validate_bound_cache(cache: np.lib.npyio.NpzFile) -> tuple[bool, str]:
    required = {
        "schema_version",
        "times",
        "target_times",
        "source_times",
        "points",
        "labels",
        "trace_distance",
        "fidelity",
        "theorem_bound",
        "width_error",
        "f41_rhs",
        "f41_valid",
        "f41_ring_rhs",
        "f41_ring_valid",
        "epsilon",
        "epsilon_ring",
        "variational_weight_floor",
        "length",
        "pole_bias",
        "initial_phi",
        "tdvp_eom",
        "tdvp_method",
        "tdvp_rtol",
        "tdvp_atol",
        "tdvp_max_step",
    }
    missing = sorted(required.difference(cache.files))
    if missing:
        return False, f"missing fields: {', '.join(missing)}"
    if int(_cache_scalar(cache, "schema_version")) != BOUND_VALIDATION_SCHEMA_VERSION:
        return False, "schema version mismatch"
    if int(_cache_scalar(cache, "length")) != BOUND_LENGTH:
        return False, "finite-ring length mismatch"
    if not _float_matches(_cache_scalar(cache, "pole_bias"), POLE_BIAS):
        return False, f"pole_bias must be {POLE_BIAS}"
    if not _float_matches(_cache_scalar(cache, "initial_phi"), INITIAL_PHI):
        return False, f"initial_phi must be {INITIAL_PHI}"
    if str(_cache_scalar(cache, "tdvp_eom")) != "tdvpfun.eom":
        return False, "TDVP equation mismatch"
    if str(_cache_scalar(cache, "tdvp_method")) != TDVP_METHOD:
        return False, "TDVP method mismatch"
    for key, expected in (
        ("tdvp_rtol", SOLVER_RTOL),
        ("tdvp_atol", SOLVER_ATOL),
        ("tdvp_max_step", SOLVER_MAX_STEP),
    ):
        if not _float_matches(_cache_scalar(cache, key), expected):
            return False, f"{key} must be {expected}"
    if not np.allclose(cache["times"], bound_times(), rtol=0.0, atol=1.0e-13):
        return False, "time grid mismatch"
    expected_points = comparison_points()[list(BOUND_POINT_INDICES)]
    expected_labels = comparison_labels()[list(BOUND_POINT_INDICES)]
    if not np.allclose(cache["points"], expected_points, rtol=0.0, atol=1.0e-15):
        return False, "point mismatch"
    if not np.array_equal(cache["labels"], expected_labels):
        return False, "label mismatch"
    return True, "ok"


def generate_bound_validation(cache_path: Path) -> None:
    """Generate same-ring local-error and defect-width validation data."""

    times = bound_times()
    target_times = np.arange(0.0, BOUND_TMAX + 0.5 * BOUND_TARGET_DT, BOUND_TARGET_DT)
    source_times = np.arange(0.0, BOUND_TMAX + 0.5 * BOUND_SOURCE_DT, BOUND_SOURCE_DT)
    basis, local_paulis = _bound_basis_and_local_paulis(BOUND_LENGTH)
