        bottom.plot(
            values["times"],
            values["width_error"][column],
            color=colors["actual"],
            label=r"actual $|\bar\omega_{\rm E}-\bar\omega_{\rm V}|$",
        )
        ring_valid = values["f41_ring_valid"][column].astype(bool)
