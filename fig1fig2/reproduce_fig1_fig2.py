def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def configure_points(manifest_path: Path, leakage_path: Path) -> None:
    """Load P1--P6 selected from the current pure-code leakage map."""

    global POINTS
    if not manifest_path.is_file():
        raise FileNotFoundError(
            f"Missing selection manifest {manifest_path}. Run "
            "explore_resonance_mode_transition.py --background-only first."
        )
    if not leakage_path.is_file():
        raise FileNotFoundError(f"Missing generated leakage map {leakage_path}")
    with manifest_path.open(encoding="utf-8") as stream:
        manifest = json.load(stream)
    if int(manifest.get("schema_version", -1)) != 1:
        raise ValueError("selection manifest schema differs")
    if manifest.get("map_sha256") != sha256(leakage_path):
        raise ValueError("selection manifest does not match the leakage map")
    protocol = manifest.get("map_protocol", {})
    if not np.isclose(
        float(protocol.get("pole_bias", np.nan)),
        POLE_BIAS,
        rtol=0.0,
        atol=1.0e-15,
    ):
        raise ValueError("selection manifest pole bias differs")
    if not np.isclose(
        float(protocol.get("initial_phi", np.nan)),
        INITIAL_PHI,
        rtol=0.0,
        atol=1.0e-15,
    ):
        raise ValueError("selection manifest initial phase differs")
    rows = manifest.get("families", {}).get("main", [])
    expected_ids = [f"P{index}" for index in range(1, 7)]
    identifiers = [str(row.get("point_id")) for row in rows]
    if identifiers != expected_ids:
        raise ValueError(
            f"selection manifest main IDs {identifiers} != {expected_ids}"
        )
    POINTS = tuple(
        (float(row["mu"]), float(row["chi"]), str(row["point_id"]))
        for row in rows
    )


