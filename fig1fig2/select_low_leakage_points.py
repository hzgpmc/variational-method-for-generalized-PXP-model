#!/usr/bin/env python3
"""Deterministically select Paper-A points from a generated leakage map.

The selection is a constrained minimization, not a list of inherited
coordinates.  Each point covers a declared physical region of the
``(mu, chi)`` plane and is the lowest-leakage grid point in that region that
respects the declared separation from previously selected points.  Shared
anchors (P1, P2, P4, and L1) are stored once and reused by the corresponding
supplementary families.

The input must be the pure-code map generated by
``explore_resonance_mode_transition.py`` with ``epsilon=1e-3`` and
``phi_i(0)=0``.  The output JSON records the map hash, numerical protocol,
selection regions, distances, and selected leakage values.
"""

