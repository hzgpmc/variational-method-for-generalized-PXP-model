@dataclass(frozen=True)
class Region:
    point_id: str
    group: str
    mu_min: float
    mu_max: float
    chi_min: float
    chi_max: float
    max_leakage: float | None = None
    note: str = ""


@dataclass(frozen=True)
class Point:
    point_id: str
    group: str
    mu: float
    chi: float
    map_mean_leakage: float
    selection_note: str


